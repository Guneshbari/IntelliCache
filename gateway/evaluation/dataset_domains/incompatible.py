def _build_incompat_metadata(
    query_text: str,
    incompat_type: str,
    target_value: Any = None,
) -> Dict[str, Any]:
    """Generates schema_version 2 metadata with deliberate contract discrepancy."""
    meta = _extractor.extract_from_text(
        text=query_text,
        provider="groq",
        model="qwen/qwen3.8-27b",
        temperature=0.7,
        max_tokens=1000,
        configured_model="BAAI/bge-small-en-v1.5",
    ).to_dict()

    if incompat_type == "provider_mismatch":
        provider_val = str(target_value or "openai")
        meta["generation_contract"]["provider"] = provider_val
        meta["llm_provider"] = provider_val
    elif incompat_type == "model_mismatch":
        model_val = str(target_value or "llama-3.3-70b-versatile")
        meta["generation_contract"]["model"] = model_val
        meta["llm_model"] = model_val
    elif incompat_type == "temperature_mismatch":
        temp_val = float(target_value if target_value is not None else 0.0)
        meta["generation_contract"]["temperature"] = temp_val
        meta["temperature"] = temp_val
    elif incompat_type == "max_tokens_mismatch":
        tokens_val = int(target_value or 2500)
        meta["generation_contract"]["max_tokens"] = tokens_val
        meta["max_tokens"] = tokens_val
    elif incompat_type == "task_kind_mismatch":
        meta["task_kind"] = {"status": "KNOWN", "value": "code_generation"}
    elif incompat_type == "missing_metadata":
        return {}
    elif incompat_type == "unsupported_version":
        meta["schema_version"] = 99
    return meta


