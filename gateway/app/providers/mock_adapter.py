"""
Mock LLM Provider Adapter for offline local testing and demonstration.
"""

import asyncio
from datetime import datetime, timezone
import time
from typing import AsyncGenerator, Optional

from ..core.contracts import (
    GenerationRequest,
    GenerationResult,
    StreamChunk,
    UsageMetrics,
)
from .interfaces import LLMProvider


class MockProvider(LLMProvider):
    """
    Simulated LLM provider that generates structured Markdown responses
    and real incremental streaming token chunks for testing without third-party API dependencies.
    """

    def __init__(
        self,
        api_key: Optional[str] = None,
        default_model: str = "mock-qwen-27b",
        **kwargs,
    ):
        self.api_key = api_key
        self.default_model = default_model

    def _generate_response_content(self, request: GenerationRequest) -> str:
        prompt_text = ""
        for m in reversed(request.messages):
            if m.role == "user":
                prompt_text = m.content
                break

        return (
            f"### Response from IntelliCache Provider\n\n"
            f"You asked:\n> {prompt_text}\n\n"
            f"Here is a demonstration response verifying the **IntelliCache** architecture:\n\n"
            f"1. **Deterministic Fingerprinting**: This response was generated by the provider on a cache miss.\n"
            f"2. **Cache Verification**: Sending this identical prompt again will result in an immediate **Exact Match (SHA-256)** hit.\n"
            f"3. **Code Sample**:\n"
            f"```python\n"
            f"import httpx\n\n"
            f"# Test IntelliCache Gateway Exact Cache\n"
            f"client = httpx.Client(base_url='http://127.0.0.1:8000')\n"
            f"response = client.post('/query', json={{\n"
            f"    'prompt': '{prompt_text[:35]}...',\n"
            f"    'model': '{request.model}'\n"
            f"}})\n"
            f"data = response.json()\n"
            f"print(f\"Cached: {{data['cached']}}, Latency: {{data['latency_ms']}}ms\")\n"
            f"```\n\n"
            f"All caching layers and diagnostics are operational!"
        )

    async def generate(self, request: GenerationRequest) -> GenerationResult:
        start_time = time.perf_counter()
        await asyncio.sleep(0.12)
        content = self._generate_response_content(request)
        elapsed_ms = (time.perf_counter() - start_time) * 1000.0

        return GenerationResult(
            text=content,
            model=request.model or self.default_model,
            usage=UsageMetrics(
                prompt_tokens=max(len(request.messages[0].content.split()), 8),
                completion_tokens=len(content.split()),
                total_tokens=max(len(request.messages[0].content.split()), 8) + len(content.split()),
            ),
            latency_ms=round(elapsed_ms, 2),
            cached=False,
            cache_type="none",
            created_at=datetime.now(timezone.utc).isoformat(),
        )

    async def stream(self, request: GenerationRequest) -> AsyncGenerator[StreamChunk, None]:
        start_time = time.perf_counter()
        content = self._generate_response_content(request)
        words = content.split(" ")

        for i, word in enumerate(words):
            await asyncio.sleep(0.015)  # 15ms per token for smooth streaming animation
            delta = word + (" " if i < len(words) - 1 else "")
            yield StreamChunk(
                delta=delta,
                done=False,
                cached=False,
                cache_type="none",
                model=request.model or self.default_model,
            )

        elapsed_ms = (time.perf_counter() - start_time) * 1000.0
        yield StreamChunk(
            delta="",
            done=True,
            cached=False,
            cache_type="none",
            model=request.model or self.default_model,
            usage=UsageMetrics(
                prompt_tokens=max(len(request.messages[0].content.split()), 8),
                completion_tokens=len(words),
                total_tokens=max(len(request.messages[0].content.split()), 8) + len(words),
            ),
            latency_ms=round(elapsed_ms, 2),
        )

    async def close(self) -> None:
        pass
